import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const harness = process.env.RSI_HARNESS ?? '/Users/black/Documents/VSCodeProject/deepseek-harness';
const { chromium } = await import(pathToFileURL(resolve(harness, 'apps/web/node_modules/playwright/index.mjs')).href);
const log = await readFile(process.argv[2] ?? '/private/tmp/rsi-frontend-host.log', 'utf8');
const launch = log.match(/http:\/\/127\.0\.0\.1:\d+\/\?token=[^\s]+/)?.[0];
assert.ok(launch);
const evidenceDir = '.cache/frontend-evidence';
await mkdir(evidenceDir, { recursive: true });
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
try {
	const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
	const errors = []; page.on('pageerror', e => errors.push(e.message));
	await page.goto(launch);
	await page.getByRole('button', { name: '设置', exact: true }).waitFor();
	const welcome = page.getByRole('button', { name: '继续', exact: true }); if (await welcome.isVisible()) await welcome.click();
	const panel = page.getByRole('complementary', { name: 'RSI 控制面板' });
	await panel.getByRole('heading', { name: 'Skill 优化' }).waitFor({ timeout: 20000 });
	const rpc = (namespace, endpoint, payload = {}) => page.evaluate(async ({ namespace, endpoint, payload }) => {
		const response = await fetch(`/${namespace}/${endpoint}`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ type: 'client-request', rpcId: crypto.randomUUID(), method: endpoint, payload }) });
		return (await response.json()).result;
	}, { namespace, endpoint, payload });
	const status = async () => { const response = await rpc('rsi-g1-fixture', 'status'); assert.equal(response.ok, true); return response.value; };
	await panel.getByText('高级设置：Skill 与设计偏好', { exact: true }).click();
	await panel.getByText('纳入已有 Skill', { exact: true }).click();
	await panel.getByText('rsi-frontend-design', { exact: true }).locator('..').getByRole('button', { name: '纳入管理', exact: true }).click();
	await panel.getByRole('button', { name: '核对来源', exact: true }).waitFor();
	const preparation = panel.getByRole('region', { name: '前端设计准备', exact: true });
	await preparation.getByLabel('页面需求', { exact: true }).fill('虚构产品落地页，使用 HTML/CSS/原生 JavaScript。必须有标题、功能介绍、可用的页内导航和键盘焦点，不使用在线字体或图片。');
	await preparation.getByRole('button', { name: '开始设计准备（不调用模型）', exact: true }).click();
	await preparation.getByLabel('配色偏好', { exact: true }).fill('浅色背景，蓝色强调');
	await preparation.getByLabel('信息密度回答方式').selectOption('no_preference');
	await preparation.getByLabel('文字排版偏好', { exact: true }).fill('标题醒目，正文清晰');
	await preparation.getByLabel('文字排版保存范围').selectOption('task');
	await preparation.getByLabel('配色偏好', { exact: true }).scrollIntoViewIfNeeded();
	await page.screenshot({ path: `${evidenceDir}/questions.png` });
	await preparation.getByRole('button', { name: '确认本批答案与保存范围', exact: true }).click();
	await preparation.getByLabel('组件形状偏好', { exact: true }).fill('少用圆角卡片');
	await preparation.getByLabel('图片使用回答方式').selectOption('skip');
	await preparation.getByLabel('动效强度偏好', { exact: true }).fill('减少移动动效');
	await preparation.getByLabel('动效强度保存范围').selectOption('personal');
	await preparation.getByRole('button', { name: '确认本批答案与保存范围', exact: true }).click();
	await preparation.getByText('已完成可选问题，可以确认上下文。', { exact: true }).waitFor();
	assert.equal((await status()).calls, 0);
	await preparation.getByRole('button', { name: '确认上下文，停止本次提问', exact: true }).click();
	await preparation.getByText('设计上下文已确认', { exact: true }).waitFor();
	const first = (await status()).state.frontend.tasks[0];
	assert.equal(first.batches.length, 2); assert.equal(first.answers.length, 6);
	await preparation.getByText('复制已确认上下文', { exact: true }).click();
	assert.deepEqual(JSON.parse(await preparation.getByLabel('已确认设计上下文', { exact: true }).inputValue()), first.frozen);
	await preparation.getByText(/管理已保存的偏好/).click();
	await preparation.getByLabel('偏好内容', { exact: true }).fill('紫色背景');
	await preparation.getByRole('button', { name: '确认保存到当前项目', exact: true }).click();
	await preparation.getByText('紫色背景', { exact: true }).waitFor();
	assert.deepEqual((await status()).state.frontend.tasks[0].frozen, first.frozen);
	await preparation.getByRole('button', { name: '预览设计优化分析', exact: true }).click();
	const preview = panel.getByLabel('分析发送内容', { exact: true }); await preview.waitFor();
	assert.deepEqual(JSON.parse(await preview.inputValue()).design, first.frozen);
	assert.equal((await status()).calls, 0);
	await panel.getByRole('button', { name: '确认范围与预算，开始分析', exact: true }).click();
	await panel.getByText('落实已确认设计偏好 · 设计偏好适配', { exact: true }).click();
	await panel.getByRole('button', { name: '保存授权草稿', exact: true }).click();
	await panel.getByText('设计偏好适配 · 草稿，未授权修改', { exact: true }).waitFor();
	assert.equal(await panel.locator('[data-rsi-owner="rsi"]').getAttribute('data-rsi-total'), '130');
	assert.equal(await panel.getByRole('button', { name: '正式授权：等待评测契约' }).isDisabled(), true);
	await page.reload();
	await panel.getByText('高级设置：Skill 与设计偏好', { exact: true }).click();
	await preparation.getByText('设计上下文已确认', { exact: true }).waitFor();
	await preparation.getByText('设计上下文已确认', { exact: true }).scrollIntoViewIfNeeded();
	await page.screenshot({ path: `${evidenceDir}/confirmed.png` });
	const final = await status();
	assert.equal(final.calls, 1); assert.equal(final.state.frontend.preferences.length, 3);
	assert.deepEqual(final.state.frontend.tasks[0].frozen, first.frozen);
	assert.deepEqual(errors, []);
	const evidence = { check: 'Frontend preparation isolated browser workflow', status: 'passed', paidRequests: 0, fixtureCalls: final.calls, fixtureTokens: 130, checks: ['bundled Skill enrollment', 'two batches of three questions', 'skip and no preference', 'explicit task/project/personal scopes', 'frozen context unchanged after preference edit', 'zero-call analysis preview', 'explicit one-shot fixture analysis', 'separate usage ledger', 'draft without modification authority', 'reload persistence'], browserErrors: errors };
	await writeFile(`${evidenceDir}/result.json`, JSON.stringify(evidence, null, '\t') + '\n'); console.log(JSON.stringify(evidence));
} catch (error) {
	for (const page of browser.contexts().flatMap(c => c.pages())) await page.screenshot({ path: `${evidenceDir}/failure.png` });
	throw error;
} finally { await browser.close(); }
